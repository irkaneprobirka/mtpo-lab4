// Ожидания простых примеров заданы явно: тест не вычисляет их через Манакера.
const examples = [['Пустая строка', '', '', 0], ['Один символ', 'a', 'a', 1], ['Два разных символа', 'ab', 'a', 2], ['Два одинаковых символа', 'aa', 'aa', 3], ['Нечётная длина', 'aba', 'aba', 4], ['Чётная длина', 'abba', 'abba', 6], ['Три одинаковых символа', 'aaa', 'aaa', 6], ['Четыре одинаковых символа', 'aaaa', 'aaaa', 10], ['Нет длинных палиндромов', 'abc', 'a', 3], ['Вложенные палиндромы', 'abacaba', 'abacaba', 12], ['Левый максимум из эталона', 'babad', 'bab', 7], ['Палиндром внутри строки', 'cbbd', 'bb', 5], ['Длина пять', 'abcba', 'abcba', 7], ['Длина семь', 'racecar', 'racecar', 10], ['Русское слово топот', 'топот', 'топот', 7], ['Русское слово казак', 'казак', 'казак', 7], ['Эмодзи по краям', '😀а😀', '😀а😀', 4], ['Два эмодзи', '😀😀', '😀😀', 3], ['Символы, похожие на границы', '^#$', '^', 3], ['Повтор специального символа', '$$$', '$$$', 6], ['Запятая внутри', 'a,a', 'a,a', 4], ['Пробел внутри', 'a a', 'a a', 4], ['Переводы строк', '\na\n', '\na\n', 4], ['Регистр имеет значение', 'Аа', 'А', 2], ['Комбинируемый знак считается отдельно', 'е\u0308', 'е', 2], ['Палиндром у правого края', 'xabba', 'abba', 7]];
// Формулы верны только для двух семейств, создаваемых генератором.
function expectedResult(text) {
  const length = text.length;
  if (/^a+$/.test(text)) {
    return {
      longest: text,
      length,
      count: length * (length + 1) / 2
    };
  }
  if (/^(?:ab)+a?$/.test(text)) {
    const longest = length % 2 === 0 ? text.slice(0, -1) : text;
    return {
      longest,
      length: longest.length,
      count: Math.floor((length + 1) ** 2 / 4)
    };
  }
  throw new Error('Нагрузочный вход должен состоять из повторов a или чередования ab');
}
